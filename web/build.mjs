// Builds the whole app into one self-contained file, dist/index.html, for GitHub Pages or any static host.
// The starter campaign, the world map, the blank character sheet, the styles and every script are inlined.
//   npm run build:web
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const renderer = join(root, 'src', 'renderer');

// 1. The starter campaign, as { "pages/home.md": "...", "data/items.json": "...", ... }.
function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}
const starterDir = join(root, 'starter');
const starter = {};
for (const file of walk(starterDir)) {
  const rel = relative(starterDir, file).split('\\').join('/');
  if (/\.(md|json)$/.test(rel)) starter[rel] = readFileSync(file, 'utf8');
}
writeFileSync(join(root, 'web', 'starter.gen.js'),
  '// Generated by web/build.mjs from starter/. Do not edit by hand.\nexport default ' + JSON.stringify(starter) + ';\n');

// 2. Every script in one bundle.
const out = await build({
  entryPoints: [join(root, 'web', 'main.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
  loader: { '.pdf': 'binary' },
  alias: { fs: join(root, 'web', 'shims', 'fs.js'), path: join(root, 'web', 'shims', 'path.js') },
  define: { __dirname: '"."' },
  logLevel: 'warning',
});
// Keep the bundle from closing its own <script> tag early.
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

// 3. One HTML file. The page's own rules are kept, loosened only to allow the inlined script and stored images.
const css = readFileSync(join(renderer, 'styles.css'), 'utf8');
let html = readFileSync(join(renderer, 'index.html'), 'utf8')
  .replace(/content="default-src[^"]*"/, `content="default-src 'self'; img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline'; frame-src 'self' about: blob:"`)
  .replace('<link rel="stylesheet" href="styles.css">', () => `<meta name="viewport" content="width=device-width, initial-scale=1">\n  <style>\n${css}\n  </style>`)
  .replace('<script type="module" src="app.js"></script>', () => `<script type="module">\n${js}\n</script>`);
if (!html.includes(js.slice(0, 200))) throw new Error('index.html no longer has the script tag this build replaces');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'index.html'), html);
writeFileSync(join(root, 'dist', '.nojekyll'), '');
console.log(`dist/index.html: ${(html.length / 1e6).toFixed(1)} MB`);
